func databaseExists(t *testing.T, name string) bool {
	t.Helper()
	conn, err := pgx.Connect(t.Context(), "")

	require.NoError(t, err)
	defer func() { _ = conn.Close(t.Context()) }()

	var exists bool
	require.NoError(
		t,
		conn.QueryRow(t.Context(), "SELECT EXISTS (SELECT FROM pg_database WHERE datname = $1)", name).Scan(&exists),
	)

	return exists
}

func TestNewGivesEachTestItsOwnDatabaseAndRemovesIt(t *testing.T) {
	var first, second string

	t.Run("first", func(t *testing.T) {
		first = databasetest.New(t).Config().ConnConfig.Database
		assert.True(t, databaseExists(t, first))
	})
	t.Run("second", func(t *testing.T) {
		second = databasetest.New(t).Config().ConnConfig.Database
	})

	assert.NotEqual(t, first, second)
	assert.False(t, databaseExists(t, first))
	assert.False(t, databaseExists(t, second))
}

// newRole creates a role with no login on the server of pool, which it removes before the database of pool.
func newRole(t *testing.T, pool *pgxpool.Pool) string {
	t.Helper()

	name := "test_role_" + strings.ToLower(rand.Text())
	ident := pgx.Identifier{name}.Sanitize()
	_, err := pool.Exec(t.Context(), "CREATE ROLE "+ident+" NOLOGIN")
	require.NoError(t, err)

	t.Cleanup(func() {
		ctx := context.WithoutCancel(t.Context())
		_, err := pool.Exec(ctx, "DROP OWNED BY "+ident+"; DROP ROLE "+ident)
		assert.NoError(t, err)
	})

	return name
}

func exec(t *testing.T, pool *pgxpool.Pool, role, statements string) {
	t.Helper()

	_, err := pool.Exec(t.Context(), strings.ReplaceAll(statements, "{role}", pgx.Identifier{role}.Sanitize()))
	require.NoError(t, err)
}

// The statements that give {role} the access of an application role.
const (
	schemaStatements = `
CREATE TABLE goose_db_version (id integer PRIMARY KEY GENERATED BY DEFAULT AS IDENTITY);
CREATE TABLE things (id bigint PRIMARY KEY GENERATED ALWAYS AS IDENTITY);`
	grantStatements = `
GRANT SELECT, INSERT, UPDATE, DELETE ON ALL TABLES IN SCHEMA public TO {role};
GRANT USAGE, SELECT ON ALL SEQUENCES IN SCHEMA public TO {role};
REVOKE ALL ON goose_db_version, goose_db_version_id_seq FROM {role};`
	defaultStatements = `
ALTER DEFAULT PRIVILEGES IN SCHEMA public GRANT SELECT, INSERT, UPDATE, DELETE ON TABLES TO {role};
ALTER DEFAULT PRIVILEGES IN SCHEMA public GRANT USAGE, SELECT ON SEQUENCES TO {role};`
)

func TestApplicationRoleProblemsIsEmptyForARoleWithDataAccessOnly(t *testing.T) {
	pool := databasetest.New(t)
	role := newRole(t, pool)
	exec(t, pool, role, schemaStatements+grantStatements+defaultStatements)

	assert.Empty(t, databasetest.ApplicationRoleProblems(t, pool, role))
}

func TestApplicationRoleProblemsIsEmptyForAnAppendOnlyTableWithSelectAndInsertOnly(t *testing.T) {
	pool := databasetest.New(t)
	role := newRole(t, pool)
	exec(
		t,
		pool,
		role,
		schemaStatements+grantStatements+defaultStatements+"REVOKE UPDATE, DELETE ON things FROM {role};",
	)

	assert.Empty(t, databasetest.ApplicationRoleProblems(t, pool, role, "public.things"))
}

func TestApplicationRoleProblemsGivesEachProblem(t *testing.T) {
	tests := map[string]struct {
		statements string
		appendOnly []string
		want       string
	}{
		"no access to a table": {
			statements: grantStatements + defaultStatements + "REVOKE DELETE ON things FROM {role};",
			want:       "public.things",
		},
		"no access to a sequence": {
			statements: grantStatements + defaultStatements + "REVOKE USAGE ON things_id_seq FROM {role};",
			want:       "public.things_id_seq",
		},
		"access to the goose table": {
			statements: grantStatements + defaultStatements + "GRANT SELECT ON goose_db_version TO {role};",
			want:       "public.goose_db_version",
		},
		"update and delete on an append-only table": {
			statements: grantStatements + defaultStatements,
			appendOnly: []string{"public.things"},
			want:       "public.things",
		},
		"truncate on an append-only table": {
			statements: grantStatements + defaultStatements + "REVOKE UPDATE, DELETE ON things FROM {role};" +
				"GRANT TRUNCATE ON things TO {role};",
			appendOnly: []string{"public.things"},
			want:       "public.things",
		},
		"no insert on an append-only table": {
			statements: grantStatements + defaultStatements + "REVOKE UPDATE, DELETE, INSERT ON things FROM {role};",
			appendOnly: []string{"public.things"},
			want:       "public.things",
		},
		"no access to a new table": {
			statements: grantStatements,
			want:       "new table",
		},
		"create on a schema": {
			statements: grantStatements + defaultStatements + "GRANT CREATE ON SCHEMA public TO {role};",
			want:       "CREATE on schema public",
		},
		"owns a table": {
			statements: grantStatements + defaultStatements + "ALTER TABLE things OWNER TO {role};",
			want:       "owns public.things",
		},
		"can log in": {
			statements: grantStatements + defaultStatements + "ALTER ROLE {role} LOGIN;",
			want:       "LOGIN",
		},
	}

	for name, tt := range tests {
		t.Run(name, func(t *testing.T) {
			pool := databasetest.New(t)
			role := newRole(t, pool)
			exec(t, pool, role, schemaStatements+tt.statements)

			problems := databasetest.ApplicationRoleProblems(t, pool, role, tt.appendOnly...)

			require.Len(t, problems, 1)
			assert.Contains(t, problems[0], tt.want)
		})
	}
}

func TestApplicationRoleProblemsGivesARoleThatDoesNotExist(t *testing.T) {
	pool := databasetest.New(t)

	assert.Equal(
		t,
		[]string{"role test_no_role does not exist"},
		databasetest.ApplicationRoleProblems(t, pool, "test_no_role"),
	)
}

func TestAsRoleGivesAPoolThatActsAsTheRole(t *testing.T) {
	pool := databasetest.New(t)
	role := newRole(t, pool)

	var current string
	require.NoError(t, databasetest.AsRole(t, pool, role).QueryRow(t.Context(), "SELECT current_user").Scan(&current))

	assert.Equal(t, role, current)
}
